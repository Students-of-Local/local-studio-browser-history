// `tychicus pi-extension` writes tychicus.ts and clears only the files an older copy of this helper wrote. The Polycarp
// app's own polycarp.ts (written as `polycarp browser pi-extension`) is never removed, only named.
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, test } from "node:test";
import { loadTs } from "./helpers/bundle-ts.mjs";

const { writePiExtension } = await loadTs(`export { writePiExtension } from "@src/pi-extension.ts";`);

const root = mkdtempSync(join(process.env.TMPDIR || tmpdir(), "tychicus-pi-"));
after(() => rmSync(root, { recursive: true, force: true }));

const dir = (name) => {
	const d = join(root, name);
	mkdirSync(d, { recursive: true });
	return d;
};
const header = (cmd) => `// Generated by \`${cmd} pi-extension\`. Talks to the browser bridge\nexport default function x() {}\n`;

test("writes tychicus.ts with the tools, and nothing else in an empty folder", () => {
	const d = dir("fresh");
	const r = writePiExtension(d);
	assert.equal(r.file, join(d, "tychicus.ts"));
	assert.deepEqual(r.removed, []);
	assert.equal(r.polycarp, undefined);
	const text = readFileSync(r.file, "utf8");
	assert.match(text, /^\/\/ Generated by `[^`]+ pi-extension`/);
	assert.match(text, /export default function tychicusExtension\(pi: ExtensionAPI\)/);
	assert.match(text, /name: "browser_navigate"/);
	assert.equal(existsSync(join(d, "polycarp.ts")), false);
});

test("an older helper's polycarp.ts or tabkyra.ts is removed, so pi doesn't register the tools twice", () => {
	for (const cmd of ["polycarp-browser", "tabkyra", "tychicus"]) {
		const d = dir(`old-${cmd}`);
		writeFileSync(join(d, "polycarp.ts"), header(cmd));
		writeFileSync(join(d, "tabkyra.ts"), header(cmd));
		const r = writePiExtension(d);
		assert.deepEqual(r.removed.sort(), [join(d, "polycarp.ts"), join(d, "tabkyra.ts")], cmd);
		assert.equal(existsSync(join(d, "polycarp.ts")), false, cmd);
		assert.equal(existsSync(join(d, "tabkyra.ts")), false, cmd);
		assert.equal(r.polycarp, undefined, cmd);
	}
});

test("the Polycarp app's polycarp.ts is kept and named; a file nobody generated is left alone", () => {
	const d = dir("polycarp-app");
	const polycarp = header("polycarp browser");
	writeFileSync(join(d, "polycarp.ts"), polycarp);
	const r = writePiExtension(d);
	assert.equal(readFileSync(join(d, "polycarp.ts"), "utf8"), polycarp);
	assert.equal(r.polycarp, join(d, "polycarp.ts"));
	assert.deepEqual(r.removed, []);

	const mine = dir("hand-written");
	writeFileSync(join(mine, "polycarp.ts"), "// my own pi extension\n");
	writeFileSync(join(mine, "tabkyra.ts"), "// Generated by something else\n");
	const r2 = writePiExtension(mine);
	assert.deepEqual(r2.removed, []);
	assert.equal(r2.polycarp, undefined);
	assert.equal(readFileSync(join(mine, "polycarp.ts"), "utf8"), "// my own pi extension\n");
	assert.ok(existsSync(join(mine, "tabkyra.ts")));
});
